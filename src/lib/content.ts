export function getCrops(lang: Lang): CropGuide[] {
  if (lang === "en") return CROPS;
  const table = lang === "mr" ? CROP_MR : CROP_HI;
  return CROPS.map((c) => ({ ...c, ...table[c.key] }));
}

export function getCrop(lang: Lang, key: CropKey): CropGuide {
  return getCrops(lang).find((c) => c.key === key) ?? getCrops(lang)[0]!;
}

